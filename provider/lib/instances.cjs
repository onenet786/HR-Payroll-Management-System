// Client installations on this server. One copy of the application code is shared by every client (a "release"
// folder under RELEASES_ROOT); each client only has its own folder with settings and data:
//
//   CLIENTS_ROOT/<slug>/.env           the client's settings (database, address, keys) — mode 600
//   CLIENTS_ROOT/<slug>/start.cjs      launcher run by the aaPanel Node project (loads the release in release.json)
//   CLIENTS_ROOT/<slug>/release.json   which release this client runs (switch = edit + restart)
//   CLIENTS_ROOT/<slug>/documents/     employee documents        BACKUP_ROOT/<slug>/  encrypted database backups
//
// A new client therefore needs no copying and no npm install: create the folder, the database and the aaPanel project.
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { spawn } = require('node:child_process');
const dotenv = require('dotenv');
const { config } = require('./config.cjs');

const clientDir = slug => path.join(config.clientsRoot, slug);
const envPath = slug => path.join(clientDir(slug), '.env');
const backupDir = slug => path.join(config.backupRoot, slug);
const projectName = slug => `hr-${slug}`;
const randomBase64 = (bytes = 32) => crypto.randomBytes(bytes).toString('base64');
const randomPassword = () => crypto.randomBytes(24).toString('base64url');

// ─── Releases ─────────────────────────────────────────────────────────────────

function listReleases() {
  if (!fs.existsSync(config.releasesRoot)) return [];
  return fs.readdirSync(config.releasesRoot, { withFileTypes: true })
    .filter(entry => entry.isDirectory() || entry.isSymbolicLink())
    .map(entry => {
      const dir = path.join(config.releasesRoot, entry.name);
      if (!fs.existsSync(path.join(dir, 'server.cjs'))) return null;
      let version = '';
      try { version = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')).version || ''; } catch { /* no package.json */ }
      const stat = fs.statSync(dir);
      return {
        name: entry.name, path: dir, version, createdAt: stat.mtime.toISOString(),
        ready: fs.existsSync(path.join(dir, 'node_modules')) && fs.existsSync(path.join(dir, 'dist', 'index.html')),
        migrations: fs.existsSync(path.join(dir, 'postgres', 'migrations')) ? fs.readdirSync(path.join(dir, 'postgres', 'migrations')).filter(name => name.endsWith('.sql')).length : 0,
      };
    })
    .filter(Boolean)
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

function releasePath(name) {
  const release = listReleases().find(item => item.name === name);
  if (!release) throw new Error(`Release "${name}" was not found in ${config.releasesRoot}.`);
  return release.path;
}

function latestRelease() {
  return listReleases().find(item => item.ready) || listReleases()[0] || null;
}

// ─── Client folder ────────────────────────────────────────────────────────────

const LAUNCHER = `// Generated by the OneNet Provider Console. Do not edit: change the release from the console.
// Runs the shared application code (release.json) with this folder's .env and data.
const fs = require('node:fs');
const path = require('node:path');
process.chdir(__dirname);
const { releasePath } = JSON.parse(fs.readFileSync(path.join(__dirname, 'release.json'), 'utf8'));
require(path.join(releasePath, 'server.cjs'));
`;

const quote = value => (/^[\w@%+=:,./-]*$/.test(String(value)) ? String(value) : JSON.stringify(String(value)));

function renderEnv(values) {
  const lines = [
    `# ${values.CLIENT_NAME} — managed by the OneNet Provider Console (${new Date().toISOString().slice(0, 10)}).`,
    '# Change settings from the console where possible; restart the Node project after editing by hand.',
    '# KEEP A COPY OF BACKUP_ENCRYPTION_KEY AND MFA_ENCRYPTION_KEY OFF THIS SERVER.',
    '',
  ];
  for (const [key, value] of Object.entries(values)) {
    if (key === 'CLIENT_NAME') continue;
    lines.push(`${key}=${quote(value ?? '')}`);
  }
  return `${lines.join('\n')}\n`;
}

function readEnv(slug) {
  try { return dotenv.parse(fs.readFileSync(envPath(slug))); } catch { return {}; }
}

/** Creates or updates the client folder. Existing secrets (database password, keys) are kept on a rewrite. */
function writeClientFolder({ slug, name, port, dbName, dbRole, dbPassword, release, appUrl, extra = {} }) {
  const dir = clientDir(slug);
  for (const sub of ['', 'documents', 'imports']) fs.mkdirSync(path.join(dir, sub), { recursive: true, mode: 0o750 });
  fs.mkdirSync(backupDir(slug), { recursive: true, mode: 0o700 });
  const previous = readEnv(slug);
  const admin = new URL(config.pgAdminUrl);
  const previousPassword = previous.DATABASE_URL ? decodeURIComponent(new URL(previous.DATABASE_URL).password) : '';
  const password = dbPassword || previousPassword;
  if (!password) throw new Error(`No database password for ${slug}: create the database step first.`);
  const dbUrl = new URL(`postgresql://${encodeURIComponent(dbRole)}:${encodeURIComponent(password)}@${admin.hostname}:${admin.port || 5432}/${dbName}`);
  const binary = tool => (config.pgBinDir ? path.join(config.pgBinDir, tool) : tool);
  const values = {
    CLIENT_NAME: name,
    DATA_BACKEND: 'postgres',
    DATABASE_URL: dbUrl.toString(),
    PG_POOL_MAX: previous.PG_POOL_MAX || '10',
    PG_SSL: 'false',
    PG_DUMP_PATH: previous.PG_DUMP_PATH || binary('pg_dump'),
    PG_RESTORE_PATH: previous.PG_RESTORE_PATH || binary('pg_restore'),
    PORT: String(port),
    HOST: '127.0.0.1',
    NODE_ENV: 'production',
    DEBUG: 'false',
    RATE_LIMIT_MAX: previous.RATE_LIMIT_MAX || '10000',
    APP_URL: appUrl,
    PORTAL_URL: appUrl,
    ALLOWED_ORIGIN: appUrl,
    MANAGED_INSTALLATION: 'true',
    VENDOR_CONSOLE_DISABLED: 'true',
    DOCUMENT_STORAGE_PATH: path.join(dir, 'documents'),
    LEGACY_IMPORT_DIR: path.join(dir, 'imports'),
    BACKUP_DIR: backupDir(slug),
    BACKUP_RETENTION_COUNT: previous.BACKUP_RETENTION_COUNT || '14',
    BACKUP_ENCRYPTION_KEY: previous.BACKUP_ENCRYPTION_KEY || randomBase64(),
    MFA_ENCRYPTION_KEY: previous.MFA_ENCRYPTION_KEY || randomBase64(),
    MFA_ISSUER: previous.MFA_ISSUER || `${name.replace(/"/g, '')} HR`,
    MFA_ENFORCE_PRIVILEGED: previous.MFA_ENFORCE_PRIVILEGED || 'false',
    SESSION_IDLE_MINUTES: previous.SESSION_IDLE_MINUTES || '30',
    SMTP_HOST: previous.SMTP_HOST ?? config.smtp.host,
    SMTP_PORT: previous.SMTP_PORT ?? config.smtp.port,
    SMTP_SECURE: previous.SMTP_SECURE ?? config.smtp.secure,
    SMTP_REQUIRE_TLS: 'true',
    SMTP_USER: previous.SMTP_USER ?? config.smtp.user,
    SMTP_PASS: previous.SMTP_PASS ?? config.smtp.pass,
    SMTP_FROM: previous.SMTP_FROM ?? config.smtp.from,
    ...extra,
  };
  fs.writeFileSync(envPath(slug), renderEnv(values), { mode: 0o600 });
  fs.writeFileSync(path.join(dir, 'start.cjs'), LAUNCHER);
  setClientRelease(slug, release);
  return { dir, env: values, dbUrl: dbUrl.toString() };
}

function setClientRelease(slug, release) {
  const target = releasePath(release);
  fs.writeFileSync(path.join(clientDir(slug), 'release.json'), `${JSON.stringify({ release, releasePath: target, setAt: new Date().toISOString() }, null, 2)}\n`);
}

function clientRelease(slug) {
  try { return JSON.parse(fs.readFileSync(path.join(clientDir(slug), 'release.json'), 'utf8')); } catch { return null; }
}

// ─── Running the application's own scripts for one client ────────────────────

/**
 * Runs a script of the client's release (scripts/postgres-migrate.cjs, postgres-backup.cjs, …) with the client's own
 * .env only — the Provider Console's environment is not passed through, so its keys never mix with the client's.
 */
function runClientScript(slug, script, args = [], extraEnv = {}, timeoutMs = 30 * 60_000) {
  const release = clientRelease(slug);
  if (!release) return Promise.reject(new Error(`Client ${slug} has no release.json.`));
  return runReleaseScript(release.releasePath, script, args, { ...readEnv(slug), ...extraEnv }, clientDir(slug), timeoutMs);
}

/** Runs scripts/<script> of a release folder with exactly the given environment (plus the system PATH). */
function runReleaseScript(releaseDir, script, args = [], scriptEnv = {}, cwd = releaseDir, timeoutMs = 30 * 60_000) {
  return new Promise((resolve, reject) => {
    const scriptPath = path.join(releaseDir, 'scripts', script);
    if (!fs.existsSync(scriptPath)) return reject(new Error(`${script} is missing in ${releaseDir}.`));
    const base = Object.fromEntries(['PATH', 'Path', 'SystemRoot', 'SYSTEMROOT', 'HOME', 'USERPROFILE', 'TEMP', 'TMP', 'TMPDIR', 'LANG', 'ComSpec', 'PATHEXT'].filter(key => process.env[key]).map(key => [key, process.env[key]]));
    // An empty working folder without .env files, so only scriptEnv applies (dotenv does not override set values).
    const child = spawn(process.execPath, [scriptPath, ...args], { cwd, env: { ...base, ...scriptEnv }, stdio: ['ignore', 'pipe', 'pipe'] });
    let output = '';
    const timer = setTimeout(() => child.kill(), timeoutMs);
    child.stdout.on('data', chunk => { output += chunk; });
    child.stderr.on('data', chunk => { output += chunk; });
    child.on('error', error => { clearTimeout(timer); reject(error); });
    child.on('close', code => {
      clearTimeout(timer);
      if (code === 0) resolve(output.trim());
      else reject(new Error(`${script} failed (exit ${code}): ${output.trim().split('\n').slice(-4).join(' ')}`));
    });
  });
}

function listBackupFiles(slug) {
  const dir = backupDir(slug);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(name => /\.dump\.enc$/.test(name)).map(name => {
    const stat = fs.statSync(path.join(dir, name));
    return { file: name, bytes: stat.size, createdAt: stat.mtime.toISOString() };
  }).sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

module.exports = {
  clientDir, envPath, backupDir, projectName, randomPassword, randomBase64,
  listReleases, releasePath, latestRelease, writeClientFolder, setClientRelease, clientRelease, readEnv, runClientScript, runReleaseScript, listBackupFiles,
};
